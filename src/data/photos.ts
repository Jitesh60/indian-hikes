/** A sized, cropped, format-negotiated URL from Unsplash's image CDN. */
export function photoUrl(key: PhotoKey, width = 1600) {
  return `${photos[key].src}?ixlib=rb-4.1.0&auto=format&fit=crop&q=78&w=${Math.round(width)}`;
}

/** Unique photographers, for the credits page. */
export function photoCredits() {
  const seen = new Map<string, { by: string; user: string; ids: string[] }>();
  for (const p of Object.values(photos) as PhotoDef[]) {
    const c = seen.get(p.user) ?? { by: p.by, user: p.user, ids: [] };
    if (!c.ids.includes(p.id)) c.ids.push(p.id);
    seen.set(p.user, c);
  }
  return [...seen.values()].sort((a, b) => a.by.localeCompare(b.by));
}
